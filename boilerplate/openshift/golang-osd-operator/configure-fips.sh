#!/usr/bin/env bash

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
CONVENTION_DIR="${REPO_ROOT}/boilerplate/openshift/golang-osd-operator"
PRE_V1_SDK_MANAGER_DIR="${REPO_ROOT}/cmd/manager"

if [[ -d "${PRE_V1_SDK_MANAGER_DIR}" ]]; then
  MAIN_DIR="${PRE_V1_SDK_MANAGER_DIR}"
else
  MAIN_DIR="${REPO_ROOT}"
fi

FIPS_FILE="${MAIN_DIR}/fips.go"

# Byte-exact contents that 'make ensure-fips' may replace with the current
# template, oldest first. Anything else is treated as consumer code and is
# left untouched. The contents are inlined because consumers copy this script
# on its own. Keep this list in sync with is_unmodified_boilerplate_fips_file
# in the convention's 'update' script, which decides the same question.
#
#   1: crypto/tls/fipsonly template, pre-'//go:build' syntax (2022-04-27).
#   2: the same template once '//go:build' was added (2022-11-14).
#   3: template 2 with the fmt.Println results explicitly discarded. This one
#      was not generated by boilerplate: consumers applied it when errcheck
#      started flagging the unchecked call. It is accepted because it is a
#      single byte-stable edit that cannot carry consumer logic, and the
#      current template drops the fmt.Println altogether.
#   4: first crypto/fips140 assertion, gated on 'boilerplate_fips_assertion'.
#   5: the same assertion once it moved back to the 'fips_enabled' tag,
#      before '//go:debug fips140=on' became part of the template.
PREVIOUS_FIPS_TEMPLATE_COUNT=5

previous_fips_template() {
  case "$1" in
  1)
    cat <<'EOF'
// +build fips_enabled

// BOILERPLATE GENERATED -- DO NOT EDIT
// Run 'make ensure-fips' to regenerate

package main

import (
	_ "crypto/tls/fipsonly"
	"fmt"
)

func init() {
	fmt.Println("***** Starting with FIPS crypto enabled *****")
}
EOF
    ;;
  2)
    cat <<'EOF'
//go:build fips_enabled
// +build fips_enabled

// BOILERPLATE GENERATED -- DO NOT EDIT
// Run 'make ensure-fips' to regenerate

package main

import (
	_ "crypto/tls/fipsonly"
	"fmt"
)

func init() {
	fmt.Println("***** Starting with FIPS crypto enabled *****")
}
EOF
    ;;
  3)
    cat <<'EOF'
//go:build fips_enabled
// +build fips_enabled

// BOILERPLATE GENERATED -- DO NOT EDIT
// Run 'make ensure-fips' to regenerate

package main

import (
	_ "crypto/tls/fipsonly"
	"fmt"
)

func init() {
	_, _ = fmt.Println("***** Starting with FIPS crypto enabled *****")
}
EOF
    ;;
  4)
    cat <<'EOF'
//go:build boilerplate_fips_assertion
// +build boilerplate_fips_assertion

// BOILERPLATE GENERATED -- DO NOT EDIT
// Run 'make ensure-fips' to regenerate

package main

import "crypto/fips140"

func init() {
	// Assert that FIPS mode is enabled via GODEBUG=fips140=on (or =only)
	if !fips140.Enabled() {
		panic("CRITICAL: Application startup aborted. FIPS 140 mode is NOT enabled!")
	}
}
EOF
    ;;
  5)
    cat <<'EOF'
//go:build fips_enabled
// +build fips_enabled

// BOILERPLATE GENERATED -- DO NOT EDIT
// Run 'make ensure-fips' to regenerate

package main

import "crypto/fips140"

func init() {
	// Assert that FIPS mode is enabled via GODEBUG=fips140=on (or =only)
	if !fips140.Enabled() {
		panic("CRITICAL: Application startup aborted. FIPS 140 mode is NOT enabled!")
	}
}
EOF
    ;;
  *)
    # Emit a sentinel as well as failing: an index with no case arm must never
    # produce empty output, or it would compare equal to an empty fips.go and
    # that file would be silently overwritten.
    printf 'NO PREVIOUS FIPS TEMPLATE NUMBERED %s\n' "$1"
    echo "[ERROR] No previous FIPS template numbered $1; PREVIOUS_FIPS_TEMPLATE_COUNT does not match the templates below it." >&2
    return 1
    ;;
  esac
}

is_previous_fips_template() {
  local index
  for ((index = 1; index <= PREVIOUS_FIPS_TEMPLATE_COUNT; index++)); do
    if cmp -s "${FIPS_FILE}" <(previous_fips_template "${index}"); then
      return 0
    fi
  done
  return 1
}

if [[ -e "${FIPS_FILE}" ]] && ! cmp -s "${FIPS_FILE}" "${CONVENTION_DIR}/fips.go.tmplt" && ! is_previous_fips_template; then
  echo "[ERROR] ${FIPS_FILE} exists and is not a recognized boilerplate FIPS template; refusing to overwrite it. Review or remove it before building with FIPS_ENABLED=true." >&2
  exit 1
fi

echo "Writing FIPS startup assertion to ${FIPS_FILE}"
cp "${CONVENTION_DIR}/fips.go.tmplt" "${FIPS_FILE}"
